export type T = (key: Key, vars?: Record<string, string>) => string;

export function translator(lang: Language): T {
  const dict = DICTS[lang] ?? en;
  return (key, vars) => {
    let s = dict[key] ?? en[key];
    for (const [k, v] of Object.entries(vars ?? {})) s = s.replace(`{${k}}`, v);
    return s;
  };
}

